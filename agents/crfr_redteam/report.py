"""Publication of the attack success rate per version (backlog E7.3)."""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

LABELS = {"document": "trapped document", "ticket": "malicious ticket", "tool_description": "poisoned tool description"}


def load_history(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return json.loads(path.read_text(encoding="utf-8"))["versions"]


def publish(path: Path, entry: dict, today: dt.date | None = None) -> list[dict]:
    """Replace the entry of this version (or add it), keep the others, sort by version."""
    history = [e for e in load_history(path) if e["version"] != entry["version"]]
    history.append({**entry, "recorded": (today or dt.date.today()).isoformat()})
    history.sort(key=lambda e: tuple(int(p) for p in e["version"].split(".")))
    path.write_text(json.dumps({"versions": history}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return history


def markdown(history: list[dict]) -> str:
    lines = [
        "# Indirect prompt injection: attack success rate per version",
        "",
        "Generated by `make redteam-report` from `agents/scenarios/indirect.toml`; do not edit by hand.",
        "",
        "The bench assumes a fully compromised model that always follows the injected instruction, so",
        "the rate measures the controls around the model, not the model. Without any control every attack",
        "succeeds (column `unprotected`), which shows that the bench can see a success. The model's own",
        "resistance is measured separately by `make redteam-live` with real credentials.",
        "",
        "| Version | Recorded | Scenarios | ASR unprotected | ASR kit | "
        + " | ".join(f"ASR {LABELS[f]}" for f in LABELS)
        + " |",
        "|---|---|---|---|---|" + "---|" * len(LABELS),
    ]
    for e in history:
        kit = e["configurations"]["kit"]
        fams = [kit["by_family"].get(f, {}).get("asr") for f in LABELS]
        lines.append(
            f"| {e['version']} | {e['recorded']} | {kit['scenarios']} | "
            f"{e['configurations']['unprotected']['asr']:.0%} | {kit['asr']:.0%} | "
            + " | ".join("n/a" if a is None else f"{a:.0%}" for a in fams)
            + " |"
        )
    latest = history[-1]
    lines += ["", f"## Scenarios of version {latest['version']}", "", "| Scenario | Family | Sector | OWASP | Kit |",
              "|---|---|---|---|---|"]  # fmt: skip
    for r in latest["configurations"]["kit"]["results"]:
        verdict = f"blocked ({r['blocked_by']})" if r["blocked_by"] else "**succeeded**"
        lines.append(f"| `{r['id']}` | {LABELS[r['family']]} | {r['sector']} | {', '.join(r['owasp'])} | {verdict} |")
    return "\n".join(lines) + "\n"
